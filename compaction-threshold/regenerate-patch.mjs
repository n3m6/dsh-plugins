/**
 * Rebuild cordis.patch.yml from the installed Standard preset.
 *
 * Run after a DSH upgrade so the preset override does not pin an old list:
 *   node regenerate-patch.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'

/** Resolve an installed package from the profile, then the dsh installation. */
function resolvePackage(specifier) {
  const bases = [
    process.argv[2],
    process.env.DSH_PROFILE_DIR,
    join(homedir(), '.dsh', 'profiles', 'web'),
    join(homedir(), '.dsh', 'profiles'),
    process.cwd(),
  ].filter((base) => base !== undefined)
  for (const base of bases) {
    try {
      return createRequire(join(base, 'package.json')).resolve(specifier)
    } catch {
      // Try the next resolution base.
    }
  }
  throw new Error(`cannot resolve ${specifier}`)
}

const webApp = dirname(resolvePackage('@deepseek-ai/dsh-web-app/package.json'))
const source = readFileSync(join(webApp, 'presets', 'standard.patch.yml'), 'utf8')

const rowStart = source.indexOf('    - id: preset-standard')
if (rowStart < 0) throw new Error('standard preset row not found')
const afterRow = source.slice(rowStart)
const configHeader = '\n      config:\n'
const configAt = afterRow.indexOf(configHeader)
if (configAt < 0) throw new Error('preset config not found')

const dedented = afterRow
  .slice(configAt + configHeader.length)
  .split('\n')
  .map((line) => (line.startsWith('    ') ? line.slice(4) : line))
  .join('\n')
const backend = "'@local/dsh-compaction-threshold/backend'"
const replaced = dedented.replace("'@deepseek-ai/dsh-compaction-basic'", backend)
if (!replaced.includes(backend)) throw new Error('compaction-basic row not found')
if (replaced.includes("'@deepseek-ai/dsh-compaction-basic'")) {
  throw new Error('more than one compaction-basic row in the Standard preset')
}

const patch = `# Compaction threshold bundle.
#
# 1. Global preference entry: its volatile \`thresholdTokens\` field is what the
#    Settings row edits. It is a profile entry so the form service can serve it.
# 2. Standard preset override: the shipped preset is restated with its
#    compaction backend swapped for this bundle's backend, which reads the
#    preference live. The rest of the preset is byte-for-byte the shipped list.
#
# Generated by regenerate-patch.mjs from:
#   ${join(webApp, 'presets', 'standard.patch.yml')}
- insert:
    - id: compaction-threshold-settings
      name: '@local/dsh-compaction-threshold'
      config:
        thresholdTokens: 300000

- id: preset-standard
  name: '@deepseek-ai/dsh-agent-preset'
  config:
${replaced}`

writeFileSync(join(import.meta.dirname, 'cordis.patch.yml'), patch)
console.log(`wrote cordis.patch.yml (${patch.split('\n').length} lines)`)
